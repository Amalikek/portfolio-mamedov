let lang = localStorage.getItem("portfolio-lang") || "ru";
let currentGallery = [];
let currentKey = "";
let currentIndex = 0;

const langToggle = document.getElementById("langToggle");
const menuBtn = document.getElementById("menuBtn");
const nav = document.querySelector(".nav");
const lightbox = document.getElementById("lightbox");
const lightboxImage = document.getElementById("lightboxImage");
const lightboxVideo = document.getElementById("lightboxVideo");
const lightboxCaption = document.getElementById("lightboxCaption");

function applyLanguage(next) {
  lang = next;
  localStorage.setItem("portfolio-lang", lang);
  document.documentElement.lang = lang;
  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const key = el.getAttribute("data-i18n");
    if (translations[lang][key] != null) el.textContent = translations[lang][key];
  });
  langToggle.textContent = lang === "ru" ? "RU / EN" : "EN / RU";
  document.title =
    lang === "ru" ? "Мамедов Амаль — Portfolio" : "Amal Mamedov — Portfolio";
  if (!lightbox.hidden && currentKey) updateCaption();
}

function updateCaption() {
  const title = galleryTitles[lang][currentKey] || "";
  lightboxCaption.textContent = `${title} · ${currentIndex + 1}/${currentGallery.length}`;
}

function stopVideo() {
  lightboxVideo.pause();
  lightboxVideo.removeAttribute("src");
  lightboxVideo.load();
}

function showMedia(src) {
  if (isVideo(src)) {
    lightboxImage.hidden = true;
    lightboxImage.removeAttribute("src");
    lightboxVideo.hidden = false;
    lightboxVideo.setAttribute("playsinline", "");
    lightboxVideo.setAttribute("webkit-playsinline", "");
    lightboxVideo.src = src;
    lightboxVideo.load();
  } else {
    stopVideo();
    lightboxVideo.hidden = true;
    lightboxImage.hidden = false;
    lightboxImage.src = src;
  }
}

function openLightbox(key, index = 0) {
  currentKey = key;
  currentGallery = galleries[key] || [];
  if (!currentGallery.length) return;
  currentIndex = index;
  showMedia(currentGallery[currentIndex]);
  updateCaption();
  lightbox.hidden = false;
  document.body.style.overflow = "hidden";
  document.body.style.position = "fixed";
  document.body.style.width = "100%";
}

function closeLightbox() {
  stopVideo();
  lightbox.hidden = true;
  lightboxImage.src = "";
  lightboxImage.hidden = true;
  lightboxVideo.hidden = true;
  lightboxCaption.textContent = "";
  document.body.style.overflow = "";
  document.body.style.position = "";
  document.body.style.width = "";
}

function showSlide(step) {
  if (!currentGallery.length) return;
  stopVideo();
  currentIndex =
    (currentIndex + step + currentGallery.length) % currentGallery.length;
  showMedia(currentGallery[currentIndex]);
  updateCaption();
}

document.querySelectorAll(".work").forEach((work) => {
  const key = work.dataset.gallery;
  const open = () => openLightbox(key, 0);
  work.querySelector(".btn-open").addEventListener("click", open);
  work.querySelector(".work-visual").addEventListener("click", open);
});

langToggle.addEventListener("click", () => applyLanguage(lang === "ru" ? "en" : "ru"));
